const fs = require("node:fs");
const path = require("node:path");

const packageRoot = __dirname;
const scaffoldRoot = path.join(packageRoot, "app-v2-scaffold");
const output = path.join(packageRoot, "src", "app-v2-scaffold.generated.ts");
const paths = [
  ".gitignore",
  ".mako/app.yaml",
  "README.md",
  "eslint.config.js",
  "index.html",
  "package.json",
  "pnpm-lock.yaml",
  "tsconfig.json",
  "tsconfig.app.json",
  "tsconfig.node.json",
  "vite.config.ts",
  "src/App.tsx",
  "src/main.tsx",
  "src/styles.css",
  "src/vite-env.d.ts",
];

const files = paths.map(filePath => ({
  path: filePath,
  contents: fs.readFileSync(path.join(scaffoldRoot, filePath), "utf8"),
  executable: false,
}));

const source = `// Generated by generate-app-v2-scaffold.cjs. Do not edit directly.
export interface AppV2ScaffoldFile {
  path: string;
  contents: string;
  executable: boolean;
}

export const AppV2ScaffoldFiles: readonly AppV2ScaffoldFile[] = ${JSON.stringify(files, null, 2)};

export function createAppV2Scaffold(): AppV2ScaffoldFile[] {
  return AppV2ScaffoldFiles.map(file => ({ ...file }));
}
`;

fs.writeFileSync(output, source);
